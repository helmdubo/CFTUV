"""Тождество точных величин: ключ считает свой хэш ОДИН раз, а не каждый раз.

ЧТО ЗДЕСЬ ЛЕЧИТСЯ, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. Ключи вхождений и портов
несут точные величины: `point_key` — это `(x.terms, y.terms)`, то есть пара
кортежей с `Fraction` внутри, а `time_key` — `(dividend, divisor.terms)`. Такой
ключ хэшируется КАЖДЫМ словарным вопросом заново, а `Fraction.__hash__` в
CPython считает модульный обратный `pow(denominator, -1, 2**61 - 1)`. На wall
2.001 density 0 это 2 943 335 вызовов `Fraction.__hash__` на домен; контрфакт с
кэширующим хэшем дал 15.95 s против 7.47 s при ПОБИТОВО тех же ответах и тех же
единицах бюджета (`artifacts/lazy_frozen_hydration/where_the_seconds_go.py`).
Адреса вопросов сняты отдельно (`artifacts/exact_identity_intern/
hash_callers.py`): 935 861 вызов приходит на `overlay.spans[leaf]`, 819 181 — на
`overlay.vertices.get(ref)`, то есть на два словаря тождества.

ПОЧЕМУ ПОДКЛАСС `tuple`, А НЕ НОВЫЙ ТИП АТОМА. Ключ обязан остаться
ПОДСТАВИМЫМ: его сравнивают с обычными кортежами (`incident.point_key ==
leaf.occurrence[1]`), из него восстанавливают точку (`point_from_key`), его
сортируют по `repr` (`superlevel._same_time_component`), и `repr` уходит в
дайджест. Подкласс `tuple` даёт всё это ТОЖДЕСТВЕННО: `repr`, `==`, `<`,
индексация, распаковка и ЗНАЧЕНИЕ хэша совпадают с обычным кортежем до бита.
Отдельный тип-атом с целочисленным id пришлось бы учить каждой из этих ролей, и
любая забытая роль стала бы молчаливым расхождением — ровно тем, что этот
репозиторий запрещает.

ЗАМЕНЫ ГЛОБАЛЬНОГО ТИПА НЕТ. `Fraction` не патчится: подмена `__hash__` у
общего типа — это изменение поведения всего процесса, включая чужой код, и
кэш по `id(self)` корректен лишь пока объект жив. Здесь запоминает ключ, а не
тип; кэш живёт ровно столько, сколько живёт сам ключ.

ИНВАРИАНТ, НА КОТОРОМ ВСЁ СТОИТ, И ОН СИЛЬНЕЕ ИНТЕРНИРОВАНИЯ. Пул
интернированных атомов даёт `intern(x) is intern(y) <=> x == y`, и любая ошибка
владения пулом (два пула, вытеснение, чужой прогон) превращает равные величины
в неравные. Здесь равенство НЕ зависит ни от какого пула: два ключа равны тогда
и только тогда, когда равны их содержимые кортежи, и ключ равен обычному
кортежу с тем же содержимым. Поэтому смешение представлений внутри одного
прогона безопасно ПО ПОСТРОЕНИЮ, а не по дисциплине, и режим «старое
представление» ниже не может дать другой ответ — только другую цену.

ЧТО ЭТО НЕ ЧИНИТ. Хэш запоминается у ключа, а не у `Fraction`, поэтому ПЕРВОЕ
хэширование каждого построенного ключа по-прежнему стоит модульных обратных по
числу коэффициентов. Цена карточки поэтому равна ЧИСЛУ ПОСТРОЕННЫХ КЛЮЧЕЙ, а не
числу словарных вопросов, и разница между этими двумя числами измерена:
2 943 335 вопросов против нескольких десятков тысяч построений.
"""

from __future__ import annotations

from enum import Enum


class ExactIdentityKeyV1(tuple):
    """Кортеж-ключ точной величины, помнящий свой хэш.

    `__slots__` здесь нет и быть не может: у подтипа `tuple` непустой
    `__slots__` запрещён интерпретатором. Цена — один указатель на инстанс
    (64 байта против 56 у голого кортежа) плюс словарь на первый вызов хэша.
    Ключи живут ровно столько, сколько живут структуры тождества пакета, и
    умирают вместе с ними: отдельного реестра, который надо было бы чистить,
    здесь нет.

    Значение хэша — РОВНО `tuple.__hash__`, а не «другой, но тоже годный».
    Иначе ключ и обычный кортеж с тем же содержимым разъехались бы по
    словарям, оставаясь равными по `==`, — это худший вид молчаливой ошибки.
    """

    def __hash__(self) -> int:  # noqa: D105 — смысл описан в докстринге класса
        try:
            return self._exact_identity_hash
        except AttributeError:
            value = tuple.__hash__(self)
            self._exact_identity_hash = value
            return value


class ExactIdentityModeV1(str, Enum):
    """Представление ключей тождества. Ответ от него не зависит — только цена.

    `CACHED` — рабочий путь: ключ помнит свой хэш.
    `LEGACY_TUPLE` — прежнее представление: голый кортеж, хэш считается заново
    каждым словарным вопросом. Он существует не как флаг совместимости, а как
    ВТОРАЯ СТОРОНА теневой сверки: новое представление обязано быть побитово
    равно старому, и это проверяется прогоном корпуса, а не рассуждением
    (`kernel/tests/test_exact_identity_shadow.py`).
    """

    CACHED = "CACHED"
    LEGACY_TUPLE = "LEGACY_TUPLE"


# Режим держится модульной переменной, и это решение, а не небрежность.
# Ключи строятся в СВОБОДНЫХ функциях (`_event_point_key`, `_time_key`,
# `_sparse_occurrences`), у которых нет ни строителя, ни транзакции в подписи;
# провести туда параметр значило бы протащить его через десяток чужих подписей
# ради переключателя, нужного одним воротам. Опасности «глобальное состояние
# меняет ответ» здесь нет по построению: оба представления РАВНЫ друг другу и
# дают ОДИН И ТОТ ЖЕ хэш, поэтому переключение посреди прогона не способно
# разделить равные величины. Продуктовый путь режим не трогает вовсе.
_MODE: list[ExactIdentityModeV1] = [ExactIdentityModeV1.CACHED]


def identity_mode() -> ExactIdentityModeV1:
    return _MODE[0]


def set_identity_mode(mode: ExactIdentityModeV1) -> ExactIdentityModeV1:
    """Сменить представление ключей; вернуть прежнее. Только для ворот."""

    previous = _MODE[0]
    _MODE[0] = ExactIdentityModeV1(mode)
    return previous


class legacy_identity:
    """Контекст «старого представления»: голые кортежи и никакой памяти пролёта.

    Оба механизма карточки выключаются ОДНИМ переключателем намеренно: ворота
    сверяют «старое представление против нового», а не два независимых флага,
    и разделённый переключатель позволил бы зазеленеть сверке, в которой одна
    из половин молча осталась включённой.
    """

    __slots__ = ("_previous",)

    def __enter__(self) -> "legacy_identity":
        self._previous = set_identity_mode(ExactIdentityModeV1.LEGACY_TUPLE)
        return self

    def __exit__(self, *_exception) -> None:
        set_identity_mode(self._previous)


def identity_key(items) -> tuple:
    """Ключ тождества из готового кортежа значений.

    В режиме `LEGACY_TUPLE` возвращается обычный кортеж — то самое
    представление, которое было до карточки, и та же цена.
    """

    if _MODE[0] is ExactIdentityModeV1.LEGACY_TUPLE:
        return tuple(items)
    return ExactIdentityKeyV1(items)


def exact_point_key(point) -> tuple:
    """Каноническое тождество точки события: `(x.terms, y.terms)`.

    Одно определение на весь фронт. До карточки эта пара собиралась в шести
    местах руками, и любое из них могло разойтись с остальными молча.
    """

    return identity_key((point.x.terms, point.y.terms))
