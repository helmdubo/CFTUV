"""Объявленные величины авторского НАМЕРЕНИЯ. Лист дерева импортов.

Здесь только числа и их обоснование — ни одного импорта из пакета. Модуль
появился, когда допуск намерения понадобился ДВУМ независимым восстановлениям:

* `source_grid` восстанавливает задуманное ПОЛОЖЕНИЕ вершины (привязка к
  решётке источника);
* `_canonical_angle` восстанавливает задуманное ОТНОШЕНИЕ сторон (канонический
  угол до селектора плотности).

Оба обязаны читать ОДНУ величину: две копии одного допуска разошлись бы, и
поле увидело бы, что «задуманно прямой» для решётки и «задуманно прямой» для
счёта — разные множества углов. Прямой импорт между этими модулями даёт цикл
(`source_grid` → `reference.angle_measure` → `reference` → `compile` →
`_canonical_angle`), поэтому величины живут в листе.
"""

from __future__ import annotations

from fractions import Fraction


# Решение владельца, `DECISIONS.md` за 2026-07-25. Деталей мельче сантиметра в
# игровом пространстве нет; максимальный габарит — 100 м. Шаг берётся у НИЖНЕЙ
# границы, поэтому деталь на него не влияет вовсе — она двигает только точку,
# в которой окно закрывается.
DECAL_DETAIL = Fraction(1, 100)

# Объявленная авторская угловая ошибка: насколько угол может отклониться от
# задуманного отношения и всё ещё считаться задуманным. Категория допуска —
# AUTHORING_INTENT: он применяется у двери восстановления намерения, а не в
# геометрии, и ниже по конвейеру решения идут на восстановленном факте.
AUTHOR_ANGULAR_ERROR = Fraction(7, 10**6)

# Допуск ВОССТАНОВЛЕНИЯ канонического отношения сторон перед селектором плотности
# (`_canonical_angle`): угол, отклонившийся от канона не более чем на эту величину,
# получает СИМВОЛИЧЕСКИЙ канонический факт. Масштаб — художника, а не машины:
# шум моделирования на полевых мешах 0.005–0.03 градуса (дверь `building` патч 10:
# вершина 245, 90.0053 градуса, лежала за допуском 7e-6 рад = 0.0004 градуса и
# переходила границу замкнутой ячейки, d2 H=2 вместо H=1), честные почти прямые
# углы начинаются с 0.4 градуса (`building.004` патч 0, 90.56). 1745e-6 рад — это
# 0.099985 градуса: НЕДОБОР до 0.1 (ошибаемся в сторону отказа). Это ДРУГАЯ
# величина, чем `AUTHOR_ANGULAR_ERROR`: тот держит привязку источника к решётке
# (положение вершины, дверь `source_grid`), и два допуска намеренно разошлись
# решением владельца 2026-10-03; в реестре допусков им разные записи.
CANONICAL_RESTORATION_ARTIST_ERROR = Fraction(1745, 10**6)


