def noise_surface(record: dict, *, patch: PatchId):
    """`(вершины, грани, треугольники)` по записи патча: имена вершин `vN`, грани `fN`, треугольники `tNNN`."""

    ids = {name: SourceVertexId(name) for name in record["vertices"]}
    vertices = tuple(
        SourceVertexV1(ids[name], LocalPoint3V1(*position))
        for name, position in record["vertices"].items()
    )
    faces = tuple(
        SourceFaceV1(
            face_id=SourceFaceId(f"f{index:03d}"),
            patch_id=patch,
            vertex_cycle=tuple(ids[name] for name in cycle),
            edge_cycle=tuple(PhysicalEdgeId(f"e{index:03d}_{k}") for k in range(len(cycle))),
            polygon_normal=LocalVector3V1(0.0, 0.0, 1.0),
            triangle_ids=(),
        )
        for index, cycle in enumerate(record["faces"])
    )
    triangles = tuple(
        SurfaceTriangleV1(
            triangle_id=SurfaceTriangleId(f"t{index:03d}"),
            source_face_id=SourceFaceId(f"f{face:03d}"),
            vertex_ids=(ids[first], ids[second], ids[third]),
            physical_edge_ids=(None, None, None),
            triangle_normal=LocalVector3V1(0.0, 0.0, 1.0),
        )
        for index, (first, second, third, face) in enumerate(record["triangles"])
    )
    return vertices, faces, triangles
